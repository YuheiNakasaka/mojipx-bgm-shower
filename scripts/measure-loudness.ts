// Renders every track in a headless browser and writes src/content/songs/loudness.ts,
// a gain per track that brings each one to the library's median loudness.
// Run with `npm run loudness` after adding or changing songs.
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';

type Measured = { readonly id: string; readonly rms: number; readonly peak: number };

const PORT = 5199;
const LIMITS = [0.5, 2] as const;

const server = await createServer({ server: { port: PORT, strictPort: true }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.goto(`http://localhost:${PORT}/`);
  const measured: readonly Measured[] = await page.evaluate(async () => {
    // Served by the Vite dev server above; the module is resolved in the page, not here.
    const url = '/src/tools/loudness.ts';
    const tool: { measureAll: () => Promise<readonly Measured[]> } = await import(/* @vite-ignore */ url);
    return tool.measureAll();
  });
  const sorted = [...measured].map((m) => m.rms).sort((a, b) => a - b);
  const median = sorted[Math.floor(sorted.length / 2)] ?? 1;
  const gains = measured.map((m) => [m.id, Math.min(LIMITS[1], Math.max(LIMITS[0], median / m.rms))] as const);
  const body = gains.map(([id, g]) => `  '${id}': ${g.toFixed(3)},`).join('\n');
  writeFileSync(
    'src/content/songs/loudness.ts',
    `// Generated by \`npm run loudness\`: a gain per track that evens out how loud the tracks sound.\nexport const LOUDNESS: Readonly<Record<string, number>> = {\n${body}\n};\n`,
  );
  for (const m of measured) console.log(`${m.id.padEnd(24)} rms ${m.rms.toFixed(4)} peak ${m.peak.toFixed(3)}`);
} finally {
  await browser.close();
  await server.close();
}
